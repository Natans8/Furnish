"""Layer 2: the database as the Lua data file an addon loads.

``Data.lua`` declares one global, ``FurnishData``, holding its tables and the two meta
values. ``wmo`` lists each root file's sets with their index, set id, name and placement
count, which is everything a window needs before a set is chosen. ``blobs`` holds each
set's placements as one printable string, in the order they spawn, decoded by the reader
only when that set is asked for. ``maps`` says which sets each map placement draws, by map
id and unique id. ``wmo`` is keyed by the root's file id, which is what a selected object's
record reports, and ``entries`` turns a gameobject entry, the number a lookup line prints,
into that file. ``models`` names the model each spawned display draws, so a set can say
what it holds without the client's help.
"""

import sqlite3
from collections.abc import Iterable
from dataclasses import dataclass
from itertools import groupby
from operator import itemgetter
from pathlib import Path

from tqdm import tqdm

from furnish import FORMAT
from furnish.codec import Row, chunked, encode
from furnish.order import trail

LINE_WIDTH = 4000
"""How wide a blob's lines are. Lua keeps the breaks inside a long string, and the encoding
has none in its alphabet, so the reader drops them before it decodes."""


@dataclass(slots=True)
class Sizes:
    """What the file weighs, by part, in bytes."""

    wmo: int = 0
    blank: int = 0
    entries: int = 0
    blobs: int = 0
    maps: int = 0
    models: int = 0
    total: int = 0


def export(database: Path, out: Path) -> Sizes:
    """Write ``Data.lua`` from a layer 1 database and say what it weighs.

    Args:
        database: The SQLite file ``furnish build`` wrote.
        out: The Lua file to write.
    """
    connection = sqlite3.connect(database)
    meta = dict(connection.execute("SELECT key, value FROM meta"))
    if meta.get("format") != str(FORMAT):
        raise ValueError(f"database format {meta.get('format')!r} is not {FORMAT}")
    parts = [
        "-- Generated by furnish export; do not edit. The reader is Reader.lua beside it.\n",
        f"FurnishData = {{ format = {FORMAT}, build = {_string(meta.get('build', ''))} }}\n",
    ]
    sizes = Sizes()
    wmo = "".join(_wmo(connection))
    blank = "".join(_blank(connection))
    entries = "".join(_entries(connection))
    blobs = "".join(_blobs(connection))
    maps = "".join(_maps(connection))
    models = "".join(_models(connection))
    sizes.wmo, sizes.blank, sizes.entries = len(wmo), len(blank), len(entries)
    sizes.blobs, sizes.maps, sizes.models = len(blobs), len(maps), len(models)
    parts += [wmo, blank, entries, blobs, maps, models]
    text = "".join(parts)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    sizes.total = len(text)
    return sizes


def _wmo(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.wmo = {\n"
    rows = connection.execute(
        'SELECT w.file, w."index", w."set", s.name,'
        ' (SELECT count(*) FROM placements p WHERE p."set" = w."set")'
        ' FROM wmo_sets w JOIN sets s ON s.id = w."set" ORDER BY w.file, w."index"'
    )
    for file_id, group in groupby(rows, key=itemgetter(0)):
        entries = "".join(
            f" {{{index},{set_id},{_string(name or '')},{count}}},"
            for _, index, set_id, name, count in group
        )
        yield f"  [{file_id}] = {{{entries} }},\n"
    yield "}\n"


def _blank(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.blank = {\n"
    for (file_id,) in connection.execute("SELECT file FROM blank_roots ORDER BY file"):
        yield f"  [{file_id}] = true,\n"
    yield "}\n"


def _entries(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.entries = {\n"
    rows = connection.execute("SELECT entry, file FROM entries ORDER BY entry")
    for entry, file_id in rows:
        yield f"  [{entry}] = {file_id},\n"
    yield "}\n"


def _blobs(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.blobs = {\n"
    sets = connection.execute("SELECT id FROM sets ORDER BY id").fetchall()
    for (set_id,) in tqdm(sets, desc="sets", unit="set"):
        rows = connection.execute(
            "SELECT display, x, y, z, qx, qy, qz, qw, scale FROM placements"
            ' WHERE "set" = ? ORDER BY seq',
            (set_id,),
        )
        blob = encode(
            trail(
                [Row(d, (x, y, z), (qx, qy, qz, qw), s) for d, x, y, z, qx, qy, qz, qw, s in rows]
            )
        )
        yield f"  [{set_id}] = [[\n" + "\n".join(chunked(blob, LINE_WIDTH)) + "]],\n"
    yield "}\n"


def _maps(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.maps = {\n"
    rows = connection.execute('SELECT map, uid, "set" FROM map_sets ORDER BY map, uid, "set"')
    for map_id, by_map in groupby(rows, key=itemgetter(0)):
        yield f"  [{map_id}] = {{\n"
        for uid, by_uid in groupby(by_map, key=itemgetter(1)):
            sets = "".join(f" {set_id}," for _, _, set_id in by_uid)
            yield f"    [{uid}] = {{{sets} }},\n"
        yield "  },\n"
    yield "}\n"


def _models(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.models = {\n"
    for display, name in connection.execute("SELECT display, name FROM models ORDER BY display"):
        yield f"  [{display}] = {_string(name)},\n"
    yield "}\n"


def _string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
