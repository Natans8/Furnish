"""Layer 2: the database as the Lua data file an addon loads.

``Data.lua`` declares one global, ``FurnishData``, holding three tables and the two meta
values. ``wmo`` lists each display id's sets with their index, set id, name and placement
count, which is everything a window needs before a set is chosen. ``blobs`` holds each
set's placements as one printable string, decoded by the reader only when that set is
asked for. ``maps`` says which sets each map placement draws, by map id and unique id.
"""

import sqlite3
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

from tqdm import tqdm

from furnish import FORMAT
from furnish.codec import Row, chunked, encode

LINE_WIDTH = 4000
"""How wide a blob's lines are; Lua reads a long string whatever its line breaks."""


@dataclass(slots=True)
class Sizes:
    """What the file weighs, by part, in bytes."""

    wmo: int = 0
    blobs: int = 0
    maps: int = 0
    total: int = 0


def export(database: Path, out: Path) -> Sizes:
    """Write ``Data.lua`` from a layer 1 database and say what it weighs.

    Args:
        database: The SQLite file ``furnish build`` wrote.
        out: The Lua file to write.
    """
    connection = sqlite3.connect(database)
    meta = dict(connection.execute("SELECT key, value FROM meta"))
    if meta.get("format") != str(FORMAT):
        raise ValueError(f"database format {meta.get('format')!r} is not {FORMAT}")
    parts = [
        "-- Generated by furnish export; do not edit. The reader is Reader.lua beside it.\n",
        f"FurnishData = {{ format = {FORMAT}, build = {_string(meta.get('build', ''))} }}\n",
    ]
    sizes = Sizes()
    wmo = "".join(_wmo(connection))
    blobs = "".join(_blobs(connection))
    maps = "".join(_maps(connection))
    sizes.wmo, sizes.blobs, sizes.maps = len(wmo), len(blobs), len(maps)
    parts += [wmo, blobs, maps]
    text = "".join(parts)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    sizes.total = len(text)
    return sizes


def _wmo(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.wmo = {\n"
    rows = connection.execute(
        'SELECT w.display, w."index", w."set", s.name,'
        ' (SELECT count(*) FROM placements p WHERE p."set" = w."set")'
        ' FROM wmo_sets w JOIN sets s ON s.id = w."set" ORDER BY w.display, w."index"'
    )
    current: int | None = None
    for display, index, set_id, name, count in rows:
        if display != current:
            if current is not None:
                yield " },\n"
            yield f"  [{display}] = {{"
            current = display
        yield f" {{{index},{set_id},{_string(name or '')},{count}}},"
    if current is not None:
        yield " },\n"
    yield "}\n"


def _blobs(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.blobs = {\n"
    sets = connection.execute("SELECT id FROM sets ORDER BY id").fetchall()
    for (set_id,) in tqdm(sets, desc="sets", unit="set"):
        rows = connection.execute(
            'SELECT display, x, y, z, qx, qy, qz, qw, scale FROM placements WHERE "set" = ?'
            " ORDER BY seq",
            (set_id,),
        )
        blob = encode(
            Row(d, (x, y, z), (qx, qy, qz, qw), s) for d, x, y, z, qx, qy, qz, qw, s in rows
        )
        yield f"  [{set_id}] = [[\n" + "\n".join(chunked(blob, LINE_WIDTH)) + "]],\n"
    yield "}\n"


def _maps(connection: sqlite3.Connection) -> Iterable[str]:
    yield "FurnishData.maps = {\n"
    rows = connection.execute('SELECT map, uid, "set" FROM map_sets ORDER BY map, uid, "set"')
    current_map: int | None = None
    current_uid: int | None = None
    for map_id, uid, set_id in rows:
        if map_id != current_map:
            if current_map is not None:
                yield " },\n  },\n"
            yield f"  [{map_id}] = {{\n"
            current_map, current_uid = map_id, None
        if uid != current_uid:
            if current_uid is not None:
                yield " },\n"
            yield f"    [{uid}] = {{"
            current_uid = uid
        yield f" {set_id},"
    if current_map is not None:
        yield " },\n  },\n"
    yield "}\n"


def _string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
